# ## Gold: Asset Utilization Dashboard
# Fleet health per region — what needs replacing, what's costing the most.

# CELL ********************

silver_assets = spark.table("silver_fixed_assets")

gold_assets = (
    silver_assets
    .groupBy("region", "category")
    .agg(
        count("*").alias("asset_count"),
        spark_round(spark_sum("acquisition_cost"), 0).alias("total_acquisition_cost"),
        spark_round(spark_sum("net_book_value"), 0).alias("total_net_book_value"),
        spark_round(spark_sum("accumulated_depreciation"), 0).alias("total_depreciation"),
        spark_round(avg("age_years"), 1).alias("avg_age_years"),
        spark_round(avg("useful_life_years"), 1).alias("avg_useful_life"),
        spark_round(spark_max("age_years"), 1).alias("oldest_asset_years"),
    )
    .withColumn(
        "depreciation_pct",
        spark_round(col("total_depreciation") / col("total_acquisition_cost") * 100, 1)
    )
    .withColumn(
        "remaining_life_pct",
        spark_round((1 - col("avg_age_years") / col("avg_useful_life")) * 100, 1)
    )
    .withColumn(
        "replacement_urgency",
        when(col("remaining_life_pct") < 20, "URGENT")
        .when(col("remaining_life_pct") < 40, "PLAN")
        .otherwise("OK")
    )
    .withColumn(
        "fleet_health",
        when(col("replacement_urgency") == "URGENT", "🔴 Replace within 1-2 years")
        .when(col("replacement_urgency") == "PLAN", "🟡 Plan replacement")
        .otherwise("🟢 Healthy")
    )
    .withColumn("_gold_refreshed_at", current_timestamp())
    .orderBy("region", "category")
)

gold_assets.write.format("delta").mode("overwrite").saveAsTable("gold_asset_utilization")
row_count = spark.table("gold_asset_utilization").count()
print(f"✅ gold_asset_utilization: {row_count} rows")
gold_assets.show(truncate=False)


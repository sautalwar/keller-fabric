# ## Gold: Regional P&L Summary
# Budget vs Actuals rolled up by region and quarter — the CFO's view.

# CELL ********************

silver_budgets = spark.table("silver_regional_budgets")

gold_pnl = (
    silver_budgets
    .groupBy("region", "fiscal_year", "quarter", "currency")
    .agg(
        spark_round(spark_sum("budget_amount"), 0).alias("total_budget"),
        spark_round(spark_sum("actual_amount"), 0).alias("total_actuals"),
        spark_round(spark_sum("forecast_amount"), 0).alias("total_forecast"),
        spark_round(spark_sum("variance"), 0).alias("total_variance"),
        spark_round(avg("variance_pct"), 1).alias("avg_variance_pct"),
        spark_round(avg("forecast_accuracy_pct"), 1).alias("avg_forecast_accuracy"),
        count("*").alias("department_count"),
    )
    .withColumn(
        "rag_status",
        when(col("avg_variance_pct") > 10, "RED")
        .when(col("avg_variance_pct") > 5, "AMBER")
        .when(col("avg_variance_pct") < -10, "RED")
        .when(col("avg_variance_pct") < -5, "AMBER")
        .otherwise("GREEN")
    )
    .withColumn(
        "budget_health",
        when(col("rag_status") == "GREEN", "On Track")
        .when(col("rag_status") == "AMBER", "Needs Attention")
        .otherwise("Action Required")
    )
    .withColumn("_gold_refreshed_at", current_timestamp())
    .orderBy("region", "fiscal_year", "quarter")
)

gold_pnl.write.format("delta").mode("overwrite").saveAsTable("gold_regional_pnl")
row_count = spark.table("gold_regional_pnl").count()
print(f"✅ gold_regional_pnl: {row_count} rows")
gold_pnl.show(truncate=False)


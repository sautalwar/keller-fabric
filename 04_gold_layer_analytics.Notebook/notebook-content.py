# ## Gold: Executive KPI Scorecard
# One row per region — the board-level view. Power BI connects directly to this table.

# CELL ********************

# Regional budget performance
budget_kpis = (
    spark.table("gold_regional_pnl")
    .groupBy("region")
    .agg(
        spark_round(spark_sum("total_budget"), 0).alias("annual_budget"),
        spark_round(spark_sum("total_actuals"), 0).alias("annual_actuals"),
        spark_round(avg("avg_variance_pct"), 1).alias("budget_variance_pct"),
        spark_round(avg("avg_forecast_accuracy"), 1).alias("forecast_accuracy_pct"),
    )
)

# Regional asset health
asset_kpis = (
    spark.table("gold_asset_utilization")
    .groupBy("region")
    .agg(
        spark_sum("asset_count").alias("total_assets"),
        spark_round(spark_sum("total_acquisition_cost"), 0).alias("total_fleet_value"),
        spark_round(spark_sum("total_net_book_value"), 0).alias("total_book_value"),
        spark_round(avg("depreciation_pct"), 1).alias("avg_depreciation_pct"),
        spark_round(avg("remaining_life_pct"), 1).alias("avg_remaining_life_pct"),
    )
)

# Regional headcount
headcount_kpis = (
    spark.table("silver_employee_regions")
    .groupBy("region")
    .agg(
        count("*").alias("headcount"),
        spark_sum(when(col("is_manager") == True, 1).otherwise(0)).alias("manager_count"),
    )
)

# Join everything into one executive scorecard
gold_scorecard = (
    budget_kpis
    .join(asset_kpis, "region", "left")
    .join(headcount_kpis, "region", "left")
    .withColumn(
        "overall_rag",
        when(
            (col("budget_variance_pct") > 10) | (col("avg_remaining_life_pct") < 20),
            "RED"
        )
        .when(
            (col("budget_variance_pct") > 5) | (col("avg_remaining_life_pct") < 40),
            "AMBER"
        )
        .otherwise("GREEN")
    )
    .withColumn(
        "executive_summary",
        when(col("overall_rag") == "RED",
             concat(lit("⚠️ "), col("region"), lit(": Requires immediate attention")))
        .when(col("overall_rag") == "AMBER",
             concat(lit("📋 "), col("region"), lit(": Monitor closely")))
        .otherwise(
             concat(lit("✅ "), col("region"), lit(": Operating within targets")))
    )
    .withColumn("_gold_refreshed_at", current_timestamp())
    .orderBy("region")
)

gold_scorecard.write.format("delta").mode("overwrite").saveAsTable("gold_executive_scorecard")
row_count = spark.table("gold_executive_scorecard").count()
print(f"✅ gold_executive_scorecard: {row_count} rows")

